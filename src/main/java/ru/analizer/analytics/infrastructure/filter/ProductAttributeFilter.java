package ru.analizer.analytics.infrastructure.filter;

import java.util.Map;

/**
 * Фильтр отбора товаров по значению атрибута.
 *
 * <p>Замысел в том, чтобы добавление фильтра по новому признаку не требовало правок
 * в построении запроса. Сейчас признак один — автор, но список полей у карточки
 * товара длинный: издательство, серия, переплёт, язык. У каждого своя таблица или
 * свой столбец, и единственное у них общее — «значение, заданное пользователем,
 * отбирает товары». Здесь это и описано: фильтр отдаёт кусок SQL-условия и свои
 * параметры, а запрос собирает их вместе.
 *
 * <p>Условие возвращается строкой не из эстетических соображений. Фильтр по автору
 * уходит в подзапрос по таблице {@code product_author}, и то же самое выразить
 * JPQL не получится: массивы и {@code exists} по произвольной таблице там не
 * поддержаны. Запросы каталога написаны на SQL — см.
 * {@link ru.analizer.analytics.infrastructure.CatalogFacts} — и фильтр
 * подставляется в них.
 *
 * <p><b>TODO(#attribute-filters)</b> — вместе с первым новым фильтром (например, по
 * издательству) проверить, достаточно ли этого интерфейса. Если понадобится
 * отбирать по нескольким значениям сразу («издательство ИЛИ издательство»), условие
 * придётся строить из нескольких предикатов, и интерфейс разрастётся.
 */
public interface ProductAttributeFilter {

    /**
     * SQL-условие без параметров запроса, а готовый к подстановке в {@code WHERE}.
     *
     * <p>Плейсхолдеры — именованные ({@code :имя}), потому что запрос собирается
     * через {@code NamedParameterJdbcTemplate}: обычный {@code JdbcTemplate} передал бы
     * {@code Map} как один параметр, и PostgreSQL ответил бы «Расширение hstore не
     * установлено».
     *
     * @param alias псевдоним товара в запросе
     * @return условие или {@code null}, если фильтр не задан и ничего не ограничивает
     */
    String predicate(String alias);

    /** Параметры к {@link #predicate(String)}. */
    Map<String, Object> parameters();
}