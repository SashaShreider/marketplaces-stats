package ru.analizer.analytics.domain;

/**
 * Состояние данных за запрошенный период.
 *
 * <p>Главная причина, по которой состояние вообще нужно: отчёт, отдающий нули за
 * незагруженный день, выглядит так же, как отчёт о дне без начислений. Пользователь
 * видит «0» и считает, что денег не было, хотя данные просто не забрали из OZON.
 */
public enum ReportStatus {
    /** Все дни периода загружены, ошибок нет. */
    READY,
    /** Часть дней загружена, часть — нет. Показаны имеющиеся. */
    PARTIAL,
    /** Ни один день не загружен. Показывать нечего. */
    NOT_LOADED,
    /** Хотя бы один день не удалось загрузить. */
    HAS_ERRORS
}