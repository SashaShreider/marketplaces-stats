package ru.analizer.sync.domain;

/**
 * Состояние дня с точки зрения синхронизации.
 */
public enum DayStatus {
    /** Ещё не обрабатывался. */
    PENDING,
    /** Идёт загрузка. */
    IN_PROGRESS,
    /** Загружен. Успех — но это не значит, что данные окончательные. */
    DONE,
    /** Загрузка завершилась ошибкой. День считается отсутствующим, а не пустым. */
    FAILED
}