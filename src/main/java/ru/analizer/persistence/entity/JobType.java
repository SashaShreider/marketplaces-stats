package ru.analizer.persistence.entity;

/**
 * Вид фоновой задачи.
 *
 * <p>Вид задан явно, потому что у задач разные правила блокировки: у финансовой
 * проверяется пересечение дат, у загрузки каталога достаточно, чтобы активная была
 * одна — иначе два процесса переписывали бы одни и те же товары.
 */
public enum JobType {

    /** Выгрузка начислений за период. */
    FINANCE,

    /** Выгрузка характеристик товаров: дат у неё нет. */
    CATALOG
}