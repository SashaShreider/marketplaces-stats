package ru.analizer.catalog.domain;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;

/**
 * Разбор значения атрибута «Автор» на отдельных авторов.
 *
 * <p>Класс чистый. Правила выведены из настоящей выгрузки
 * {@code /v4/product/info/attributes} — 108 товаров, а не придуманы. Разбирать
 * приходится два разных случая:
 * <ul>
 *   <li>4182 «Автор» — одна строка, авторы перечислены <b>через запятую</b>:
 *       «Черняев А. Ю., Ланде А. А.», «Б. И. Жильцов, В. К. Марков, В. С. Федосеев».</li>
 *   <li>105 «Автор на обложке» — значения приходят <b>отдельными элементами
 *       массива</b>: «Умнова Ирина Анатольевна», «Конюхова Ирина Анатольевна»,
 *       «Умнова-Конюхова Ирина Анатольевна». Это не один текст с разделителем, а
 *       три независимых значения одного атрибута.</li>
 * </ul>
 * Поэтому на вход принимается список значений, а не строка, и каждый элемент
 * дополнительно делится по запятой: атрибут 4182 со временем тоже может начать
 * приходить массивом, и тогда он распадётся так же, как сейчас.
 *
 * <h2>Строгий контракт: только как написано</h2>
 * Имя сохраняется ровно тем текстом, которым его написал продавец, и фильтр ищет по
 * нему точное совпадение. Ни приведения регистра, ни сведения к инициалам, ни
 * склейки разных написаний одного человека здесь нет сознательно.
 *
 * <p>В выгрузке одного и того же человека товары называют по-разному: «Сурцуков А.»,
 * «Сурцуков Анатолий», «А.В. Сурцуков», «Анатолий Васильевич Сурцуков». Автоматика
 * склеивала бы их в один ключ, но ошибалась бы и на других именах, а неверно
 * найденный товар в отчёте о продажах хуже, чем неточно заполненный фильтр.
 * Унификация — дело продавца, он может привести свои карточки к единому виду в
 * кабинете маркетплейса.
 *
 * <p><b>TODO(#author-aliases)</b> — если понадобится склейка написаний, делать её
 * не разбором строки, а таблицей соответствий: «Сурцуков А.» → канонический
 * {@code author_id}. Разбор по форме тут гарантированно ошибается на двойных
 * фамилиях и инициалах.
 */
public final class AuthorExtractor {

    /**
     * Разделители имён внутри одного значения атрибута.
     *
     * <p>Запятая подтверждена выгрузкой (4182). Точка с запятой в выгрузке не
     * встретилась, но оставлена как страховка: разделитель — это соглашение
     * маркетплейса, и смена его однажды не должна была бы потребовать правки кода.
     *
     * <p>Слово «и» разделителем <b>не</b> является: «Галина и Павел Барышниковы» —
     * это одно значение, один автор.
     *
     * <p><b>TODO(#author-separator)</b> — если OZON начнёт разделять авторов иначе
     * (например, переносом строки), правило придётся расширить; набор разделителей
     * стоит держать здесь, в одном месте.
     */
    private static final String SEPARATORS = "[;,]";

    private AuthorExtractor() {
    }

    /**
     * Разбирает все значения атрибута в отдельных авторов.
     *
     * @param rawValues значения атрибута как вернул OZON: один или несколько,
     *                  {@code null} и пустые допустимы
     * @param primary   признак основного источника: {@code true} для 4182, когда он есть
     * @return авторы в порядке появления, без повторов
     */
    public static List<Author> extract(List<String> rawValues, boolean primary) {
        List<Author> result = new ArrayList<>();
        if (rawValues == null || rawValues.isEmpty()) {
            return result;
        }
        // LinkedHashSet: сохраняем порядок появления и убираем повторы — в выгрузке
        // один и тот же человек встречается и в 4182, и в 105.
        Set<String> seen = new LinkedHashSet<>();
        int position = 0;
        for (String rawValue : rawValues) {
            if (rawValue == null || rawValue.isBlank()) {
                continue;
            }
            for (String piece : rawValue.split(SEPARATORS)) {
                // Пробелы по краям убираем: OZON их ставит непоследовательно
                // («Кондрашева Л. И. » с хвостовым пробелом встречается в выгрузке).
                // Сравнение с тем же значением из подсказки фильтра иначе не сошлось бы
                // из-за невидимого символа.
                String name = piece.trim();
                if (name.isEmpty()) {
                    continue;
                }
                if (seen.add(name)) {
                    result.add(new Author(name, primary, position++));
                }
            }
        }
        return result;
    }

    /**
     * Один автор в исходном виде.
     *
     * @param raw значение как вернул OZON — его же показываем пользователю и по
     *            нему же ищем
     */
    public record Author(String raw, boolean primary, int position) {
    }
}