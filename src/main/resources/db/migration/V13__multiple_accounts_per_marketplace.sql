-- ---------------------------------------------------------------------------
-- Несколько магазинов одного маркетплейса у одного пользователя
--
-- До сих пор действовало ограничение uq_seller_account_user_marketplace
-- UNIQUE (app_user_id, marketplace_id): один пользователь — один магазин на
-- маркетплейс. Оно выражало не техническое требование, а предположение,
-- что подключать второй кабинет незачем.
--
-- Предположение перестало верным: у одного продавца бывает несколько
-- кабинетов OZON, и каждый со своими начислениями и каталогом. Пока
-- ограничение стояло, второй магазин не заводился вовсе, а если тот же
-- Client-Id вводили повторно, ключи просто перезаписывали первый магазин —
-- вместе с его данными они оставались, но относились уже к чужим ключам.
--
-- Чем заменяем:
--
--   * uq_seller_account_user_marketplace_client UNIQUE (app_user_id,
--     marketplace_id, client_id) — не мешает завести несколько кабинетов
--     (у них разные Client-Id), но по-прежнему запрещает подключить один и
--     тот же кабинет дважды. Без него повторное подключение создавало бы
--     второй аккаунт с теми же реквизитами, дважды съедало бы квоту при
--     импорте и делило бы один кабинет на две половины в отчётах.
--
--   * idx_seller_account_user_marketplace — выбор списка магазинов
--     пользователя по платформе идёт именно так, и теперь это не точечный
--     запрос по одной строке, а выборка группы.
--
-- Что с уже существующими данными: ничего не меняется. У каждого
-- пользователя магазин на платформу и так был один, новое ограничение ему не
-- противоречит, и переносить строки не нужно. Миграция только ослабляет
-- правило.
--
-- Данные магазинов разделены колонкой seller_account_id во всех таблицах
-- импорта, и она не меняется: аналитика уже считает по аккаунту, а не по
-- маркетплейсу, поэтому два магазина одного пользователя не смешиваются.
-- ---------------------------------------------------------------------------

ALTER TABLE seller_account
    DROP CONSTRAINT uq_seller_account_user_marketplace;

ALTER TABLE seller_account
    ADD CONSTRAINT uq_seller_account_user_marketplace_client
        UNIQUE (app_user_id, marketplace_id, client_id);

CREATE INDEX idx_seller_account_user_marketplace
    ON seller_account (app_user_id, marketplace_id);