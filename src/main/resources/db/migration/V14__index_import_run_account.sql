-- Прогоны всегда выбираются по аккаунту: список, счётчик, поиск активного импорта.
-- Внешний ключ не создаёт индекс в PostgreSQL, поэтому без этого индекса каждый запрос
-- и каскадное удаление аккаунта сканировали бы всю таблицу import_run.
CREATE INDEX idx_import_run_account ON import_run (seller_account_id);
