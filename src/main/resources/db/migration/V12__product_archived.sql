-- Признак архивного товара.
--
-- Зачем это нужно:
--   * метод /v3/product/list отдаёт при visibility=ALL «все товары, кроме
--     архивных», поэтому архивный товар в каталог не попадает никогда;
--   * но начисления по нему остаются, и без его карточки суммы отчёта по товарам
--     расходятся с дневным отчётом на всю сумму продаж этого товара;
--   * без отметки в интерфейсе нельзя объяснить пользователю, почему товар с
--     продажами есть в отчёте, а в его кабинете его давно нет.
--
-- Значение по умолчанию — false, а не «известно»: обычный товар, пришедший при
-- visibility=ALL, заведомо не архивный, и переписывать ему признак незачем.
ALTER TABLE ozon_product
    ADD COLUMN archived BOOLEAN NOT NULL DEFAULT false;

-- Поиск идёт по подмножеству каталога, поэтому индекс строим вместе с признаком.
-- Отдельный индекс нужен, чтобы отчёт мог отличать архивные товары от обычных
-- прямо в выборке, не подгружая колонку построчно.
CREATE INDEX idx_ozon_product_account_archived
    ON ozon_product (seller_account_id, archived);
