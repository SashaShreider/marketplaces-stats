-- Убираем ограничение, связывавшее аккаунт с маркетплейсом и client_id.
--
-- Ограничение uq_seller_account_marketplace_client (marketplace_id, client_id)
-- появилось в V1, когда аккаунты продавцов были общими и app_user ещё не
-- существовал: один и тот же клиент OZON не должен был завестись дважды.
--
-- После V9 аккаунт принадлежит пользователю, и ограничение стало чужим:
--
--   * два разных продавца на одном маркетплейсе с одинаковым client_id больше не
--     могут завестись вместе. Клиент приложения получает 500 вместо понятного
--     ответа, хотя его собственные реквизиты верны;
--   * ошибка выглядит как сбой приложения, и по логу её не отличить от любой
--     другой нарушенной уникальности.
--
-- Что ограничение при этом НЕ делало: не мешало двум аккаунтам одного
-- пользователя на одном маркетплейсе. Это и так запрещено отдельно, ограничением
-- uq_seller_account_user_marketplace, и именно оно выражает правило «один
-- аккаунт на маркетплейс у пользователя».
--
-- То есть ограничение не защищало ни от чего, чего не защищает оставшееся, но
-- ломало подключение легитимных продавцов.
ALTER TABLE seller_account
    DROP CONSTRAINT uq_seller_account_marketplace_client;

-- client_id остаётся NOT NULL и индексируется: по нему идёт поиск аккаунта при
-- подключении, и пустое значение сделало бы поиск бессмысленным.
CREATE INDEX idx_seller_account_marketplace_client
    ON seller_account (marketplace_id, client_id);
