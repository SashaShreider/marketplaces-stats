-- Пользователи и реквизиты доступа к маркетплейсу.
--
-- Зачем это нужно:
--   * без владельца данных любой пользователь видел бы чужие начисления: все
--     таблицы висели на seller_account, который ничему не принадлежал;
--   * реквизиты OZON переезжают из .env в базу, иначе ими нельзя управлять
--     из интерфейса, а приложение нельзя развернуть на нескольких продавцов.
--
-- Ограничение MVP: почты и подтверждения нет, восстановить пароль нельзя —
-- только ручная правка базы. Когда понадобится, добавим email и сброс пароля
-- отдельной миграцией: null-колонка ничего не ломает.

CREATE TABLE app_user (
    id            BIGSERIAL PRIMARY KEY,
    login         VARCHAR(64)  NOT NULL,
    -- BCrypt. Сырой пароль не хранится и не логируется нигде.
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(255),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_app_user_login UNIQUE (login)
);

-- ---------------------------------------------------------------------------
-- Аккаунт продавца становится принадлежностью пользователя
-- ---------------------------------------------------------------------------
ALTER TABLE seller_account
    ADD COLUMN app_user_id BIGINT REFERENCES app_user (id) ON DELETE CASCADE,
    ADD COLUMN api_key      VARCHAR(255);

-- Один магазин на маркетплейс у пользователя. Ограничение живёт в схеме, а не
-- в коде: иначе рано или поздно появится путь, который его обойдёт.
ALTER TABLE seller_account
    ADD CONSTRAINT uq_seller_account_user_marketplace UNIQUE (app_user_id, marketplace_id);

-- Существующим аккаунтам владелец неизвестен. В MVP данных для восстановления
-- нет, поэтому аккаунты без пользователя просто удаляются вместе с начислениями.
DELETE FROM seller_account WHERE app_user_id IS NULL;

ALTER TABLE seller_account
    ALTER COLUMN app_user_id SET NOT NULL;

